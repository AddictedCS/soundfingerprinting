namespace SoundFingerprinting
{
    using System.Collections.Generic;
    using System.Threading;
    using System.Threading.Tasks;
    using SoundFingerprinting.Command;
    using SoundFingerprinting.Data;

    /// <summary>
    ///  Model service interface providing access to various hashes storages.
    /// </summary>
    /// <remarks>
    ///   Details about available hashes storage can be found <a href="https://github.com/AddictedCS/soundfingerprinting/wiki/Other-Storages">here</a>.
    ///   An implementation over a local storage may compute synchronously and return a completed task. A remote implementation awaits its I/O.
    /// </remarks>
    public interface IModelService : IQueryService
    {
        /// <summary>
        ///  Gets details about underlying storage (i.e. track count, hashes count etc.)
        /// </summary>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>Storage information, one entry per media type.</returns>
        Task<IReadOnlyList<ModelServiceInfo>> GetInfoAsync(CancellationToken cancellationToken = default);

        /// <summary>
        ///  Inserts new track with associated hashes into the storage.
        /// </summary>
        /// <param name="trackInfo">Track related information.</param>
        /// <param name="hashes">Instance of <see cref="AVHashes"/> generated by <see cref="FingerprintCommand"/>.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>An <see cref="InsertResult"/> describing whether the track was inserted, updated, or suppressed as a duplicate.</returns>
        /// <remarks>
        ///  Inserting track with the same <see cref="TrackInfo.Id"/> will overwrite existing hashes to provided <paramref name="hashes"/>.
        /// </remarks>
        Task<InsertResult> InsertAsync(TrackInfo trackInfo, AVHashes hashes, CancellationToken cancellationToken = default);

        /// <summary>
        ///  Updates track info <see cref="TrackInfo.Id"/> is used as the key to the object to update.
        ///  Fields that will be updated: <see cref="TrackInfo.Title"/>, <see cref="TrackInfo.Artist"/>, <see cref="TrackInfo.MetaFields"/>.
        /// </summary>
        /// <param name="trackInfo">Track to update.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>Task that completes when the track is updated.</returns>
        Task UpdateTrackAsync(TrackInfo trackInfo, CancellationToken cancellationToken = default);

        /// <summary>
        ///  Removes a track and associated hashes from the storage by track ID.
        /// </summary>
        /// <param name="trackId">Track ID to remove.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>Task that completes when the track is removed.</returns>
        Task DeleteTrackAsync(string trackId, CancellationToken cancellationToken = default);

        /// <summary>
        ///  Gets hashes for a particular track.
        /// </summary>
        /// <param name="trackId">Track identifier.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>List of hashes corresponding to track by ID.</returns>
        Task<AVHashes> ReadHashesByTrackIdAsync(string trackId, CancellationToken cancellationToken = default);

        /// <summary>
        ///  Read track by ID.
        /// </summary>
        /// <param name="trackId">Track ID to read the track.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>TrackInfo if storage contains a track with provided ID, null otherwise.</returns>
        Task<TrackInfo?> ReadTrackByIdAsync(string trackId, CancellationToken cancellationToken = default);

        /// <summary>
        ///  Read all track ids from the storage.
        /// </summary>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>Materialized list of all inserted track ids.</returns>
        Task<IReadOnlyList<string>> GetTrackIdsAsync(CancellationToken cancellationToken = default);
    }
}
